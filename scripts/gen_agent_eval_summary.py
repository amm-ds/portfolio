#!/usr/bin/env python3
"""Bake the agent-chat eval report into a typed summary module (H5).

Reads the committed per-case eval report
(``apps/agent-chat/reports/evals-kimi-for-coding.md``) and writes
``apps/showcase-web/src/lib/agentChatEvalSummary.ts`` so the Agent Chat
article renders a summary-by-case-kind table from the committed evidence —
never hand-written numbers.

Deterministic: kinds sorted, no timestamps — a re-run without report changes
produces no diff. ``--check`` fails on a stale module without rewriting it
(same pattern as gen_static_registry.py / gen_story_short.py).

Regenerate after a new eval report lands:

    uv run python scripts/gen_agent_eval_summary.py
"""

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "apps/agent-chat/reports/evals-kimi-for-coding.md"
OUT = ROOT / "apps/showcase-web/src/lib/agentChatEvalSummary.ts"

ROW_RE = re.compile(r"^\| ([^|]+) \| (\w+) \| (\w+) \| (\w+) \|$")
TOTAL_RE = re.compile(r"Passed (\d+)/(\d+) grader assertions")
MODEL_RE = re.compile(r"^Model: `([^`]+)`")


def parse_report(path: Path) -> dict:
    """Per-case pipe table -> summary counters. Raises on malformed input."""
    rows: list[tuple[str, str, str, str]] = []
    model = "unknown"
    total = None
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if m := MODEL_RE.match(stripped):
            model = m.group(1)
        if m := TOTAL_RE.search(stripped):
            total = (int(m.group(1)), int(m.group(2)))
        if m := ROW_RE.match(stripped):
            case, kind, grader, verdict = (g.strip() for g in m.groups())
            if case == "case":
                continue  # header row
            rows.append((case, kind, grader, verdict))
    if not rows:
        raise ValueError(f"{path}: no eval rows found")
    if total is None:
        raise ValueError(f"{path}: no 'Passed N/N grader assertions' totals line")

    by_kind: Counter[str] = Counter()
    by_kind_pass: Counter[str] = Counter()
    for _case, kind, _grader, verdict in rows:
        by_kind[kind] += 1
        if verdict == "pass":
            by_kind_pass[kind] += 1

    distinct_cases = {re.sub(r" \[\d/\d+\]$", "", c) for c, *_ in rows}
    repetitions = max(
        len({c for c, *_ in rows if re.sub(r" \[\d/\d+\]$", "", c) == k}) for k in distinct_cases
    )
    passed_total = sum(by_kind_pass.values())
    return {
        "model": model,
        "cases": len(distinct_cases),
        "repetitions": repetitions,
        "executions": len(distinct_cases) * repetitions,
        "assertions": len(rows),
        "passed": passed_total,
        "report_total": total,
        "by_kind": [
            {
                "kind": kind,
                "assertions": by_kind[kind],
                "passed": by_kind_pass[kind],
            }
            for kind in sorted(by_kind)
        ],
    }


def render(summary: dict) -> str:
    kinds = ",\n".join(
        f'    {{ kind: "{k["kind"]}", assertions: {k["assertions"]}, passed: {k["passed"]} }}'
        for k in summary["by_kind"]
    )
    return (
        "// Generated by scripts/gen_agent_eval_summary.py — do not hand edit.\n"
        "// Source: apps/agent-chat/reports/evals-kimi-for-coding.md (committed eval report).\n"
        "export interface AgentEvalKindSummary {\n"
        "  kind: string;\n"
        "  assertions: number;\n"
        "  passed: number;\n"
        "}\n\n"
        "export const AGENT_EVAL_SUMMARY = {\n"
        f'  report: "apps/agent-chat/reports/evals-kimi-for-coding.md",\n'
        f'  model: "{summary["model"]}",\n'
        f"  cases: {summary['cases']},\n"
        f"  repetitions: {summary['repetitions']},\n"
        f"  executions: {summary['executions']},\n"
        f"  totalAssertions: {summary['assertions']},\n"
        f"  totalPassed: {summary['passed']},\n"
        "  byKind: [\n"
        f"{kinds}\n"
        "  ],\n"
        "} as const;\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed module differs from a fresh render; do not write",
    )
    args = parser.parse_args()

    summary = parse_report(REPORT)
    text = render(summary)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"error: {OUT.relative_to(ROOT)} is stale; run scripts/gen_agent_eval_summary.py")
            return 1
        print("agent-eval-summary: OK (module matches the committed report)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({summary['passed']}/{summary['assertions']} assertions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
