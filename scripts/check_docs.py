#!/usr/bin/env python3
"""Documentation gate (docs-as-code): relative markdown links must resolve to
an existing file or heading anchor, except for git-ignored DVC outputs that
pipelines regenerate; fenced code blocks must carry a language tag;
/glossary#slug anchors referenced from apps/showcase-web/src must exist in the
glossary data. Public READMEs describe current snapshots, not wave changelogs.

Surfaces: AGENTS.md, README.md, projects/*/README.md, apps/**/README.md,
libs/**/README.md, registry/README.md, deploy/**/*.md, and first-party
docs/**/*.md. Vendored skills, dependencies, and generated third-party content
are excluded. No readability scoring or blanket punctuation rules apply to
command-heavy documentation.

Run: uv run python scripts/check_docs.py
"""

import fnmatch
import json
import re
import sys
import unicodedata
from pathlib import Path
from urllib.parse import unquote

REPO = Path(__file__).resolve().parents[1]

EXCLUDED_PARTS = {
    ".venv",
    "build",
    "dist",
    "node_modules",
    "site",
    "third_party",
    "vendor",
    "vendored",
    "venv",
}
PUBLIC_CHANGELOG_RE = re.compile(
    r"\b(?:run and wave record|revision and wave record|changelog)\b"
    r"|\bwave\s*-?\s*\d+\b",
    re.IGNORECASE,
)


def _first_party(path: Path, repo: Path) -> bool:
    rel = path.relative_to(repo)
    if any(part in EXCLUDED_PARTS for part in rel.parts):
        return False
    return rel.parts[:3] != ("docs", "engineering", "skills")


def _rglob(repo: Path, directory: str, pattern: str) -> list[Path]:
    return [
        path
        for path in sorted((repo / directory).rglob(pattern))
        if path.is_file() and _first_party(path, repo)
    ]


def doc_files(repo: Path = REPO) -> list[Path]:
    """Return the first-party instruction and documentation surfaces."""
    files = [
        repo / "AGENTS.md",
        repo / "README.md",
        *sorted((repo / "projects").glob("*/README.md")),
        *_rglob(repo, "apps", "README.md"),
        *_rglob(repo, "libs", "README.md"),
        repo / "registry" / "README.md",
        *_rglob(repo, "deploy", "*.md"),
        *_rglob(repo, "docs", "*.md"),
    ]
    return sorted({path for path in files if path.is_file()})


DOC_FILES = doc_files()

LINK_RE = re.compile(r"!?\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
SKIP_SCHEME_RE = re.compile(r"^(?:[a-z][a-z0-9+.-]*:|//)", re.IGNORECASE)
GLOSSARY_ANCHOR_RE = re.compile(r"/glossary#(?!<)([a-z0-9][a-z0-9-]*)")
# "/glossary#slug" (the literal word) is a placeholder in prose and comments,
# never a real anchor — the regex above already skips "#<slug>".
PLACEHOLDER_SLUGS = {"slug"}


def github_slug(heading: str) -> str:
    """GitHub-style heading anchor: lowercase, punctuation stripped, spaces -> hyphens."""
    text = unicodedata.normalize("NFKD", heading)
    text = "".join(c for c in text if not unicodedata.combining(c))
    text = re.sub(r"[^\w\s-]", "", text.lower(), flags=re.UNICODE)
    return re.sub(r"\s+", "-", text, flags=re.UNICODE).strip("-")


def heading_anchors(path: Path) -> set[str]:
    anchors: set[str] = set()
    seen: dict[str, int] = {}
    for line in path.read_text().splitlines():
        m = re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if not m:
            continue
        base = github_slug(m.group(2))
        if not base:
            continue
        n = seen.get(base, 0)
        seen[base] = n + 1
        anchors.add(base if n == 0 else f"{base}-{n}")
    return anchors


def fenced_spans(text: str) -> list[tuple[int, int]]:
    """(start_line, end_line) 1-based spans of fenced code blocks."""
    spans: list[tuple[int, int]] = []
    start: int | None = None
    for i, line in enumerate(text.splitlines(), 1):
        if start is None:
            if line.lstrip().startswith("```"):
                start = i
        elif line.strip().startswith("```"):
            spans.append((start, i))
            start = None
    if start is not None:
        spans.append((start, 10**9))  # unclosed fence: everything after is code
    return spans


def dvc_out(target: Path) -> bool:
    """A missing path is a valid DVC out when an ancestor .gitignore matches
    its filename: git-ignored by design, tracked by DVC, regenerated by the
    project's pipeline (reports/metrics.json, figures/*.html, detect.json…).
    Links to those artifacts are pointers, not broken links."""
    for parent in target.parents:
        if parent == REPO.parent:
            break
        gi = parent / ".gitignore"
        if gi.exists():
            for line in gi.read_text().splitlines():
                pattern = line.strip()
                if not pattern or pattern.startswith("#"):
                    continue
                pattern = pattern.lstrip("/")
                if fnmatch.fnmatch(target.name, pattern) or fnmatch.fnmatch(
                    str(target.relative_to(parent)), pattern
                ):
                    return True
    return False


def check_links(files: list[Path] | None = None) -> list[str]:
    problems: list[str] = []
    anchor_cache: dict[Path, set[str]] = {}
    for f in DOC_FILES if files is None else files:
        rel = f.relative_to(REPO)
        lines = f.read_text().splitlines()
        code = fenced_spans("\n".join(lines))
        for lineno, line in enumerate(lines, 1):
            if any(a <= lineno <= b for a, b in code):
                continue  # link syntax inside fenced code is not a link
            for m in LINK_RE.finditer(line):
                url = unquote(m.group(1)).strip()
                if SKIP_SCHEME_RE.match(url):
                    continue
                path_part, _, frag = url.partition("#")
                if not path_part:
                    target = f
                else:
                    target = (f.parent / path_part).resolve()
                    if not str(target).startswith(str(REPO)):
                        problems.append(f"{rel}:{lineno}: link escapes the repo: {url}")
                        continue
                    if target.is_dir():
                        continue
                    if not target.exists() and not dvc_out(target):
                        problems.append(f"{rel}:{lineno}: broken link -> {url}")
                        continue
                if frag and target.suffix == ".md":
                    if target not in anchor_cache:
                        anchor_cache[target] = heading_anchors(target)
                    if frag not in anchor_cache[target]:
                        problems.append(f"{rel}:{lineno}: missing anchor #{frag} in {url}")
    return problems


def check_code_fences(files: list[Path] | None = None) -> list[str]:
    problems: list[str] = []
    for f in DOC_FILES if files is None else files:
        rel = f.relative_to(REPO)
        in_fence = False
        for lineno, line in enumerate(f.read_text().splitlines(), 1):
            if not in_fence and line.lstrip().startswith("```"):
                in_fence = True
                if not line.lstrip()[3:].strip():
                    problems.append(f"{rel}:{lineno}: fenced block missing a language tag")
            elif in_fence and line.strip().startswith("```"):
                in_fence = False
    return problems


def check_current_snapshots(files: list[Path] | None = None) -> list[str]:
    """Keep wave/changelog history out of root and project READMEs."""
    problems: list[str] = []
    for f in DOC_FILES if files is None else files:
        rel = f.relative_to(REPO)
        if rel != Path("README.md") and not (
            len(rel.parts) == 3 and rel.parts[0] == "projects" and rel.name == "README.md"
        ):
            continue
        lines = f.read_text().splitlines()
        code = fenced_spans("\n".join(lines))
        for lineno, line in enumerate(lines, 1):
            if any(a <= lineno <= b for a, b in code):
                continue
            match = PUBLIC_CHANGELOG_RE.search(line)
            if match:
                problems.append(
                    f"{rel}:{lineno}: '{match.group(0)}' is development history; "
                    "move it to DESIGN.md and keep the README current"
                )
    return problems


def check_glossary_anchors() -> list[str]:
    glossary_path = REPO / "apps" / "showcase-web" / "src" / "lib" / "glossary.json"
    slugs = {e["slug"] for e in json.loads(glossary_path.read_text())}
    src = REPO / "apps" / "showcase-web" / "src"
    problems: list[str] = []
    for f in sorted(src.rglob("*")):
        if f.suffix not in {".ts", ".tsx"}:
            continue
        rel = f.relative_to(REPO)
        lines = f.read_text().splitlines()
        code = fenced_spans("\n".join(lines))
        for lineno, line in enumerate(lines, 1):
            if any(a <= lineno <= b for a, b in code):
                continue
            for m in GLOSSARY_ANCHOR_RE.finditer(line):
                if m.group(1) in PLACEHOLDER_SLUGS:
                    continue
                if m.group(1) not in slugs:
                    glossary_rel = glossary_path.relative_to(REPO)
                    problems.append(f"{rel}:{lineno}: /glossary#{m.group(1)} not in {glossary_rel}")
    return problems


def check_adr_counts() -> list[str]:
    """ADR count assertions on the two surfaces that name them in prose.

    Both files re-staled once already (said 7 when 8 ADRs existed); the
    count is derived from the ADR files themselves so this gate cannot
    drift the same way.
    """
    adr_dir = REPO / "docs" / "architecture" / "adr"
    count = len(sorted(adr_dir.glob("000[0-9]-*.md")))
    problems: list[str] = []
    llms = REPO / "llms.txt"
    m = re.search(r"decision records 0001\u2013(\d+)", llms.read_text())
    if not m or int(m.group(1)) != count:
        problems.append(f"llms.txt: ADR range 0001-{m.group(1) if m else '?'} != {count} ADR files")
    spelled = {
        1: "one",
        2: "two",
        3: "three",
        4: "four",
        5: "five",
        6: "six",
        7: "seven",
        8: "eight",
        9: "nine",
        10: "ten",
        11: "eleven",
        12: "twelve",
    }
    built = REPO / "docs" / "site" / "how-this-was-built.md"
    m = re.search(r"The (\w+) ADRs", built.read_text())
    if not m or m.group(1).lower() != spelled[count]:
        got = m.group(1) if m else "?"
        want = spelled[count]
        problems.append(f"docs/site/how-this-was-built.md: 'The {got} ADRs' != {want} ADR files")
    return problems


def collect_errors() -> list[str]:
    return [
        *check_links(),
        *check_code_fences(),
        *check_current_snapshots(),
        *check_glossary_anchors(),
        *check_adr_counts(),
    ]


if __name__ == "__main__":
    problems = collect_errors()
    if problems:
        for p in problems:
            print("ERROR:", p)
        sys.exit(1)
    print("check-docs: OK")
