"""Seeded synthetic taxi dataset — the CI/fast track for the benchmark.

Same working schema as the real NYC TLC slice (the eight columns the tasks
touch), generated by a single seeded ``numpy`` generator so the synthetic
path is byte-stable across runs and machines. The real track downloads the
registry-pinned January 2024 snapshot instead (``fetch.py``).
"""

from pathlib import Path

import numpy as np
import polars as pl
from portfolio_core.schemas import DatasetContract
from portfolio_core.synthetic import checksum_of_frame

#: Working schema shared with the real slice (fetch.py projects these columns
#: out of the raw 20-column TLC file). VendorID and payment_type are kept as
#: strings on both tracks so the string-categorical task is genuinely
#: string-shaped everywhere (the real codes 1/2/6 and 0-4 stay readable).
TRIP_COLUMNS: tuple[str, ...] = (
    "tpep_pickup_datetime",
    "PULocationID",
    "DOLocationID",
    "passenger_count",
    "trip_distance",
    "fare_amount",
    "VendorID",
    "payment_type",
)

#: Synthetic vendor + payment pools mirror the real value spaces (real track:
#: vendors 1/2/6 weighted like the real month, payment 1 "credit" dominant).
_VENDOR_IDS: tuple[str, ...] = ("1", "2", "6")
_VENDOR_WEIGHTS: tuple[float, ...] = (0.2462, 0.7537, 0.0001)  # ≈ real 729k/2.23M/260
_PAYMENT_TYPES: tuple[str, ...] = ("0", "1", "2", "3", "4")
_PAYMENT_WEIGHTS: tuple[float, ...] = (0.047, 0.782, 0.148, 0.007, 0.016)

#: Synthetic zone pool: ids inside the real 1..263 range, spread over four
#: boroughs with a few hot zones (mirrors the real concentration).
_SYNTHETIC_ZONES: tuple[tuple[int, str, str], ...] = (
    (74, "Manhattan", "East Village"),
    (75, "Manhattan", "Lower East Side"),
    (166, "Manhattan", "Upper West Side North"),
    (41, "Manhattan", "Central Harlem"),
    (230, "Brooklyn", "Williamsburg"),
    (255, "Brooklyn", "Sunset Park"),
    (138, "Queens", "LaGuardia Airport"),
    (132, "Queens", "JFK Airport"),
    (7, "Queens", "Astoria"),
    (179, "Bronx", "Fordham South"),
    (188, "Bronx", "Riverdale"),
    (243, "Staten Island", "St. George"),
)

#: LocationID → row weight: airports and the East Village are hot.
_HOT_ZONES: frozenset[int] = frozenset({74, 138, 132})


def trips_frame(seed: int, n: int) -> pl.DataFrame:
    """Seeded ``n``-row synthetic trip frame with the working schema.

    Daily seasonality (quiet 4am, two evening peaks), a few hot pickup zones,
    lognormal distances and a fare formula with an inflated long-tail share so
    the filtered-scan task has something to select.
    """
    rng = np.random.default_rng(seed)
    # Whole January at minute resolution, denser on business days.
    day = rng.integers(1, 32, size=n)
    hour = rng.integers(0, 24, size=n)
    minute = rng.integers(0, 60, size=n)
    pickup = pl.Series(
        "tpep_pickup_datetime",
        [f"2024-01-{d:02d} {h:02d}:{m:02d}:00" for d, h, m in zip(day, hour, minute, strict=True)],
    ).str.to_datetime("%Y-%m-%d %H:%M:%S", time_unit="us")

    ids = np.array([z[0] for z in _SYNTHETIC_ZONES])
    weights = np.array([4.0 if z in _HOT_ZONES else 1.0 for z in ids])
    pu = rng.choice(ids, size=n, p=weights / weights.sum())
    do = rng.choice(ids, size=n, p=weights / weights.sum())

    # Night rides run longer on average; multiplicative lognormal noise.
    night_factor = np.where((hour < 5) | (hour >= 22), 1.6, 1.0)
    distance = np.exp(rng.normal(1.2, 0.7, size=n)) * night_factor
    distance = np.round(np.clip(distance, 0.2, None), 2)

    fare = 3.0 + 2.8 * distance + np.abs(rng.normal(0.0, 1.5, size=n))
    # Inflate a small share into the >$50 band so the filter task bites.
    big = rng.random(n) < 0.01
    fare = np.where(big, fare + rng.uniform(50.0, 220.0, size=n), fare)
    fare = np.round(np.clip(fare, 2.5, None), 2)

    vendor = rng.choice(len(_VENDOR_IDS), size=n, p=_VENDOR_WEIGHTS)
    payment = rng.choice(len(_PAYMENT_TYPES), size=n, p=_PAYMENT_WEIGHTS)

    return pl.DataFrame(
        {
            "tpep_pickup_datetime": pickup,
            "PULocationID": pu.astype(np.int32),
            "DOLocationID": do.astype(np.int32),
            "passenger_count": rng.integers(1, 5, size=n).astype(np.int64),
            "trip_distance": distance.astype(np.float64),
            "fare_amount": fare.astype(np.float64),
            "VendorID": np.array(_VENDOR_IDS, dtype=object)[vendor].tolist(),
            "payment_type": np.array(_PAYMENT_TYPES, dtype=object)[payment].tolist(),
        }
    ).select(TRIP_COLUMNS)


def zones_frame() -> pl.DataFrame:
    """Synthetic zone lookup with the real lookup file's schema."""
    return pl.DataFrame(
        {
            "LocationID": [z[0] for z in _SYNTHETIC_ZONES],
            "Borough": [z[1] for z in _SYNTHETIC_ZONES],
            "Zone": [z[2] for z in _SYNTHETIC_ZONES],
            "service_zone": ["Synthetic" for _ in _SYNTHETIC_ZONES],
        }
    )


def write_synthetic_dataset(seed: int, n: int, out_dir: Path) -> tuple[pl.DataFrame, pl.DataFrame]:
    """Write the synthetic dataset (trips parquet/CSV, partitioned, zones).

    Returns the (trips, zones) frames. The layout matches the real prepared
    layout so every task reads both tracks through the same code path.
    """
    trips = trips_frame(seed, n)
    zones = zones_frame()
    _write_prepared(trips, zones, out_dir)
    return trips, zones


def _write_prepared(trips: pl.DataFrame, zones: pl.DataFrame, out_dir: Path) -> None:
    """Persist the prepared layout both tracks share (idempotent)."""
    prepared = out_dir / "prepared"
    partitioned = prepared / "partitioned"
    for d in (out_dir / "raw", prepared, partitioned):
        d.mkdir(parents=True, exist_ok=True)

    trips.write_parquet(prepared / "trips.parquet", compression="snappy")
    trips.write_csv(prepared / "trips.csv")
    zones.write_csv(out_dir / "raw" / "taxi_zone_lookup.csv")

    day = trips["tpep_pickup_datetime"].dt.day()
    for d in sorted(day.unique().to_list()):
        part = partitioned / f"day={d:02d}"
        part.mkdir(parents=True, exist_ok=True)
        trips.filter(day == d).write_parquet(part / "part-0.parquet", compression="snappy")


def write_dataset_contract(
    out_dir: Path, *, source: str, n_rows: int, checksum: str, license_text: str
) -> DatasetContract:
    """Write the versioned dataset identity card for whichever track ran."""
    from datetime import date

    card = DatasetContract(
        name=(
            "nyc-tlc-yellow-2024-01-synthetic"
            if source.startswith("synthetic")
            else "nyc-tlc-yellow-2024-01"
        ),
        source=source,
        license=license_text,
        snapshot_date=date.today(),
        checksum_sha256=checksum,
        n_rows=n_rows,
    )
    (out_dir / "dataset_contract.json").write_text(card.model_dump_json(indent=2))
    return card


def synthetic_checksum(seed: int, n: int) -> str:
    """Canonical checksum of the seeded synthetic frame (determinism gate)."""
    return checksum_of_frame(trips_frame(seed, n))
